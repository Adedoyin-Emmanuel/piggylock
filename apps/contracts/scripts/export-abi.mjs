// Writes the SavingsVault ABI to the web app as a typed `as const` module so
// the frontend always matches the compiled contract. Run after compiling.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(
  readFileSync("artifacts/contracts/SavingsVault.sol/SavingsVault.json", "utf8"),
);
const out = new URL("../../web/src/lib/savings-vault-abi.ts", import.meta.url);
mkdirSync(new URL(".", out), { recursive: true });
writeFileSync(
  out,
  `// Generated by apps/contracts/scripts/export-abi.mjs — do not edit.\n` +
    `export const savingsVaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log(`Wrote ${out.pathname}`);
